"""
database.py — ПОДКЛЮЧЕНИЕ К БАЗЕ ДАННЫХ.

Здесь всё, что связано с базой:
- engine        — «двигатель», который умеет соединяться с базой;
- async_session — фабрика сессий (сессия = одно «общение» с базой);
- Base          — общий предок для всех моделей-таблиц;
- get_session   — функция, которая выдаёт сессию обработчикам запросов;
- init_db       — создаёт таблицы при старте приложения.

Слово «асинхронный» (async) означает, что программа не «зависает», ожидая
ответа от базы, а может в это время заниматься другими запросами.
"""

# asyncio — встроенный модуль Python для асинхронной работы.
# Он нам нужен, чтобы сделать паузу (asyncio.sleep) между попытками
# подключения к базе.
import asyncio

# Импортируем инструменты SQLAlchemy для асинхронной работы с базой:
from sqlalchemy.ext.asyncio import (
    AsyncSession,          # тип «асинхронная сессия» (используем в подсказках типов)
    async_sessionmaker,    # функция, создающая «фабрику» сессий
    create_async_engine,   # функция, создающая движок подключения
)

# DeclarativeBase — современный базовый класс для описания таблиц (моделей).
from sqlalchemy.orm import DeclarativeBase

# Забираем наши настройки (там лежит строка подключения к базе).
from src.config import settings


# Создаём движок (engine). Он знает АДРЕС базы (settings.postgres_dsn)
# и умеет открывать к ней соединения.
# echo=False — не выводить в консоль каждый SQL-запрос
# (поставь True, если хочешь видеть, какие запросы уходят в базу).
engine = create_async_engine(settings.postgres_dsn, echo=False)

# Создаём «фабрику сессий». Позже вызовом async_session() мы будем
# получать новую сессию для каждого запроса.
# expire_on_commit=False — после сохранения (commit) объекты остаются
# пригодными для чтения (иначе SQLAlchemy пометил бы их «устаревшими»).
async_session = async_sessionmaker(engine, expire_on_commit=False)


# Базовый класс для всех моделей. Каждая наша таблица (например, User)
# будет наследоваться от Base. SQLAlchemy по этим классам поймёт,
# какие таблицы создавать в базе.
class Base(DeclarativeBase):
    pass  # тело пустое — нам достаточно самого факта наследования


# Это функция-зависимость (dependency) для FastAPI.
# FastAPI будет вызывать её на каждый запрос, где она нужна,
# и подставлять полученную сессию в обработчик.
async def get_session():
    # `async with` — асинхронный менеджер контекста: он сам откроет сессию,
    # а по завершении блока гарантированно её закроет (даже если была ошибка).
    async with async_session() as session:
        # yield (а не return!) отдаёт сессию наружу и «замораживает» функцию
        # до конца запроса. После ответа выполнение вернётся сюда и сессия
        # корректно закроется. Так работают зависимости FastAPI.
        yield session


# Функция создаёт все таблицы в базе, если их ещё нет.
# Вызывается один раз при старте приложения (см. main.py).
# `-> None` означает, что функция ничего не возвращает.
async def init_db() -> None:
    # Импорт моделей ВНУТРИ функции (а не сверху файла) сделан специально:
    # так мы избегаем «кольцевых» импортов и при этом гарантируем, что
    # SQLAlchemy «увидит» все таблицы до их создания.
    # `# noqa: F401` говорит линтеру: «да, импорт не используется явно — это ок».
    from src import models  # noqa: F401

    # Переменная для запоминания последней ошибки (если попытки не удадутся).
    # `Exception | None` — тип: либо ошибка, либо None (пусто).
    last_error: Exception | None = None

    # Пробуем подключиться несколько раз: база в Docker может стартовать
    # чуть медленнее приложения. range(1, 11) — числа от 1 до 10.
    for attempt in range(1, 11):
        try:
            # engine.begin() открывает соединение и транзакцию.
            async with engine.begin() as conn:
                # run_sync запускает «обычную» (синхронную) функцию create_all
                # в асинхронном движке. create_all создаёт все таблицы,
                # описанные в моделях (если их ещё нет).
                await conn.run_sync(Base.metadata.create_all)
            print("[init_db] Таблицы готовы.")
            return  # успех — выходим из функции
        except Exception as error:
            # Сюда попадаем, если база ещё не готова принять подключение.
            last_error = error  # запомним ошибку
            print(f"[init_db] Попытка {attempt}: база не готова, ждём... ({error})")
            # Пауза 2 секунды перед следующей попыткой (не блокирует программу).
            await asyncio.sleep(2)

    # Если все 10 попыток провалились — «бросаем» ошибку и останавливаем запуск.
    raise RuntimeError(f"Не удалось подключиться к базе данных: {last_error}")
