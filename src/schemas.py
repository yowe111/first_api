"""
schemas.py — СХЕМЫ PYDANTIC (ФОРМА ДАННЫХ API).

Схема описывает, КАК выглядят данные:
- которые ПРИХОДЯТ в наше API (от клиента);
- которые API ОТДАЁТ обратно.

FastAPI использует схемы, чтобы:
1) проверять входные данные (правильный ли тип, всё ли на месте);
2) превращать объекты в JSON для ответа;
3) автоматически строить документацию на странице /docs.

ВАЖНО: не путай схему и модель!
- Модель (models.py) — это таблица в базе данных.
- Схема (этот файл) — это форма данных на «границе» API.
Их разделяют специально: например, чтобы НЕ отдавать наружу хеш пароля.
"""

# BaseModel — базовый класс всех схем Pydantic.
# ConfigDict — способ задать настройки схемы.
from pydantic import BaseModel, ConfigDict


# Схема для РЕГИСТРАЦИИ. Такие данные клиент присылает, создавая аккаунт.
class UserCreate(BaseModel):
    username: str   # логин — строка (обязателен)
    email: str
    password: str   # пароль — строка (обязателен)


# Схема для ОТВЕТА о пользователе. Именно это API отдаёт наружу.
# Обрати внимание: здесь НЕТ пароля — наружу его не показываем.
class UserRead(BaseModel):
    id: int         # номер пользователя
    username: str   # его логин

    # from_attributes=True разрешает Pydantic создавать эту схему
    # напрямую из объекта модели SQLAlchemy (читая его атрибуты .id, .username).
    # Без этой настройки пришлось бы вручную превращать модель в словарь.
    model_config = ConfigDict(from_attributes=True)


# Схема ответа при успешном ВХОДЕ: возвращаем токен и его тип.
class Token(BaseModel):
    access_token: str            # сам токен (длинная строка)
    token_type: str = "bearer"   # тип токена; "bearer" — стандарт для JWT
