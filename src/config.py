"""
config.py — НАСТРОЙКИ ПРИЛОЖЕНИЯ.

Зачем нужен этот файл?
Любой программе нужны параметры: адрес базы данных, секретные ключи и т.п.
Плохо «зашивать» их прямо в код. Хорошо — держать в отдельном месте (файле .env)
и читать оттуда. Этим и занимается config.py.

Как это работает?
Библиотека pydantic-settings умеет автоматически брать значения из
переменных окружения (их задаёт docker-compose из файла .env) и складывать
в удобный Python-объект `settings`. Дальше по всему проекту мы пишем
просто `settings.secret_key` и получаем нужное значение.
"""

# Импортируем два инструмента из библиотеки pydantic-settings:
# - BaseSettings: базовый класс, от которого наследуют классы с настройками.
# - SettingsConfigDict: способ указать доп. параметры (например, файл .env).
from pydantic_settings import BaseSettings, SettingsConfigDict


# Объявляем класс с настройками. Наследуемся от BaseSettings —
# это даёт «магию»: значения полей автоматически подтянутся из окружения/.env.
class Settings(BaseSettings):
    # Ниже перечислены поля-настройки. Запись `имя: тип` — это подсказка типа.
    # Она говорит, какого типа ожидается значение (строка, число и т.д.).

    # Строка подключения к базе данных (её называют DSN).
    # Тип str = строка (текст). Значения по умолчанию нет,
    # поэтому его ОБЯЗАТЕЛЬНО нужно задать в .env, иначе будет ошибка.
    postgres_dsn: str

    # Секретный ключ, которым подписываются токены входа (JWT).
    # Здесь через `= "..."` задано значение по умолчанию:
    # если в .env его нет — возьмётся вот эта строка.
    secret_key: str = "super-secret-key-change-me"

    # Сколько минут «живёт» токен после входа. Тип int = целое число.
    # По умолчанию 60 минут.
    access_token_expire_minutes: int = 60

    # Спец-поле model_config настраивает поведение самого класса настроек.
    model_config = SettingsConfigDict(
        env_file=".env",             # откуда читать: из файла .env
        env_file_encoding="utf-8",   # кодировка файла (utf-8 понимает русский)
        extra="ignore",              # лишние переменные из .env просто игнорировать
                                     # (например, DB_USER нужен docker-compose, но не коду)
    )


# Создаём ОДИН объект настроек на всё приложение.
# В момент создания pydantic прочитает .env и заполнит поля.
# Другие файлы делают `from src.config import settings` и пользуются им.
settings = Settings()
